def get_alerts() -> List[Dict[str, Any]]:
    """
    Read intrusion detection alerts from the CSV file.

    Handles edge cases:
      - File does not exist yet (no attacks occurred): returns an empty list [].
      - File exists but is empty: returns an empty list [].
      - Malformed rows: handles defensively without crashing the web server.

    Returns:
        List[Dict[str, Any]]: List of alert dictionaries reversed so newest threats
                              appear at the top.
    """
    if not os.path.isfile(CSV_FILE_PATH) or os.path.getsize(CSV_FILE_PATH) == 0:
        return []

    alerts: List[Dict[str, Any]] = []

    try:
        with open(CSV_FILE_PATH, mode="r", newline="", encoding="utf-8") as csv_file:
            reader = csv.DictReader(csv_file)
            for row in reader:
                cleaned_row = {
                    (k.strip() if k else ""): (v.strip() if v else "")
                    for k, v in row.items()
                }
                alerts.append(cleaned_row)
    except (OSError, csv.Error) as err:
        app.logger.error(f"Error reading alerts CSV file: {err}")
        return []

    # Reverse list so newest threats appear at the top
    alerts.reverse()
    return alerts


@app.route("/")
def index():
    """
    Main dashboard view.
    Renders the Dark-Mode SOC console template from templates/index.html,
    falling back to the embedded template string if needed.
    Subsequent updates are pulled asynchronously via AJAX from /api/alerts.
    """
    alerts = get_alerts()
    try:
        return render_template("index.html", alerts=alerts)
    except Exception:
        return render_template_string(SOC_DASHBOARD_TEMPLATE, alerts=alerts)


@app.route("/api/alerts")
def api_alerts():
    """
    Phase 10 Task 2:
    REST API endpoint returning the reversed list of alerts as JSON.
    Called every 3 seconds by the frontend AJAX polling loop to update the
    dashboard asynchronously without full page refreshes.
    """
    alerts = get_alerts()
    return jsonify(alerts)


